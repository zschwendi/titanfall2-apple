#!/usr/bin/env python3
"""Self-test of tools/gamedata/fetch.py against a made-up install in a temporary directory.

    tools/gamedata/selftest.py          prints "gamedata selftest: N checks passed" or the failures

No game file and no other machine: the "install" is a directory of generated bytes, the
"game" directory another, and --source names the first.  Expected values come from the rules
in fetch.py's first comment and from the bytes generated here.
"""
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
FETCH = os.path.join(HERE, 'fetch.py')
B = 4096                        # --block and --small of this test
BIG = 2048 * B                  # large enough for the volume to keep its holes as holes
checks = failures = 0


def data(seed, n):
    """n bytes that differ from block to block (the period, 251, divides no block size)."""
    period = bytes((seed + i) % 251 for i in range(251))
    return (period * (n // 251 + 1))[:n]


def check(cond, what):
    global checks, failures
    checks += 1
    if not cond:
        failures += 1
        print('FAILED: %s' % what)


def tool(*args, env=None):
    p = subprocess.run([sys.executable, FETCH] + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=env)
    return p.returncode, p.stdout + p.stderr


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'wb') as fp:
        fp.write(content)


def fake_ssh(root):
    """A directory to put first on PATH: its `ssh` writes its arguments to <root>/ssh.called and
    fails.  No test here may reach a real ssh; one that would is seen and is harmless."""
    bindir = os.path.join(root, 'bin')
    os.makedirs(bindir)
    with open(os.path.join(bindir, 'ssh'), 'w') as fp:
        fp.write('#!/bin/sh\nprintf "%%s\\n" "$@" >> %s\nexit 255\n' % os.path.join(root, 'ssh.called').replace(' ', '\\ '))
    os.chmod(os.path.join(bindir, 'ssh'), 0o755)
    env = dict(os.environ)
    env['PATH'] = bindir + os.pathsep + env.get('PATH', '')
    return env


def names_and_commands(root):
    """Finding 10 of docs/reviews/night-2026-10-11-code-review.md, the tool's side: a name of
    the listing or of the manifest cannot leave GAME and MAP or end a line, and what goes to
    ssh is a host after `--` and one quoted command.  Expected values: fetch.py's first
    comment and the brief of unit fix-review-night, section 3."""
    sys.path.insert(0, HERE)
    import fetch
    src, game = os.path.join(root, 'install'), os.path.join(root, 'g', 'game')
    write(os.path.join(src, 'a/ok.bin'), data(1, 3 * B))
    os.makedirs(game)
    mapdir = os.path.realpath(game) + '.partial'
    base = ['--game', game, '--source', src, '--block', str(B), '--small', str(B), '--floor-gb', '0']
    s, out = tool(*base, '--manifest')
    check(s == 0, 'a clean listing makes a manifest: %d %s' % (s, out))
    good = open(os.path.join(mapdir, 'manifest.tsv')).read()

    # A name with a carriage return (str.splitlines would cut the line there).
    write(os.path.join(src, 'a/evil\rf\t1\t..'), b'x')
    s, out = tool(*base, '--manifest')
    check(s == 5 and 'control character' in out, 'a name with a control character is refused when the manifest is made: %d %s' % (s, out))
    check(open(os.path.join(mapdir, 'manifest.tsv')).read() == good, 'and the manifest that was there is as it was')
    os.unlink(os.path.join(src, 'a/evil\rf\t1\t..'))

    # The listing's parser: lines end at \n only, and the three fields are checked.
    got = list(fetch.parse_listing(b'f\t5\ta/b.bin\nd\t4096\ta\nf\t1\tx\rf\t1\t../y\n'))
    check(got == [('f', 5, 'a/b.bin'), ('d', 0, 'a'), ('f', 1, 'x\rf\t1\t../y')], 'the listing is cut at newlines only: %r' % got)
    check(fetch.bad_name(got[2][2]) is not None, 'and the name that held a carriage return is one the manifest refuses')
    for raw in (b'f\tx\ta\n', b'q\t1\ta\n', b'f\t1\n', b'just text\n'):
        try:
            list(fetch.parse_listing(raw))
            check(False, 'a listing line that is not three fields is refused: %r' % raw)
        except fetch.Fail as f:
            check(f.status == 5, 'a listing line that is not three fields ends with status 5: %r' % raw)
    for name in ('../x', 'a/../../x', 'a/./b', 'a//b', '/abs', 'a/..', '..', 'a\\b', 'a\x7fb', 'a\x85b', 'a\u2028b', ''):
        check(fetch.bad_name(name) is not None, 'the name %r is refused' % name)
    for name in ('r2/paks/Win64/big(01).starpak', 'a b/c..d/.e', 'bin/x64_retail/engine.dll', "it's $HOME `x`"):
        check(fetch.bad_name(name) is None, 'the name %r is kept' % name)

    # A listing that names a way out of the directories: no manifest is written from it.
    class Leaving:
        name = 'a made-up source'

        def listing(self):
            return [('f', 1, 'a/ok.bin'), ('f', 5, '../../outside.bin')]
    store = fetch.Store(game, 0, B, B, out=open(os.devnull, 'w'))
    try:
        store.write_manifest(Leaving())
        check(False, 'a listing with a .. component is refused')
    except fetch.Fail as f:
        check(f.status == 5 and 'component' in str(f), 'a listing with a .. component is refused: %s' % f)
    check(open(os.path.join(mapdir, 'manifest.tsv')).read() == good, 'and no manifest was written from it')
    store.lock_fp.close()               # this process held the map's lock: the commands below take it themselves
    store.lock_fp = None

    # A manifest that someone edited to name a file outside: not used, nothing written outside.
    write(os.path.join(root, 'leak.bin'), b'the install does not have this')
    with open(os.path.join(mapdir, 'manifest.tsv'), 'w') as fp:
        fp.write(good + 'f\t30\t../leak.bin\n')
    s, out = tool(*base, '../leak.bin')
    check(s == 6 and 'not used' in out, 'a manifest name that leaves the directories: the manifest is not used: %d %s' % (s, out))
    check(not os.path.lexists(os.path.join(root, 'g', 'leak.bin')), 'and nothing was written outside the game directory')
    s, out = tool(*base, 'a/ok.bin')
    check(s == 6 and not os.path.lexists(os.path.join(game, 'a/ok.bin')), 'nor is any other file fetched with it: %d' % s)
    with open(os.path.join(mapdir, 'manifest.tsv'), 'w') as fp:
        fp.write(good)
    for bad in ('../leak.bin', 'a/../../leak.bin', 'a/ok.bin/..'):
        for build in (store.host_path, store.data_path, store.ranges_path):
            try:
                build(bad)
                check(False, '%s(%r) is refused' % (build.__name__, bad))
            except fetch.Fail as f:
                check(f.status == 6, '%s(%r) is refused' % (build.__name__, bad))

    # What goes to ssh.  The fake ssh on PATH records a call; none of these may make one.
    env = fake_ssh(root)
    called = os.path.join(root, 'ssh.called')
    for source in ('-oProxyCommand=touch ' + os.path.join(root, 'pwned') + ':/x', '-v:/x', 'host;id:/x', 'ho st:/x', 'host:relative/dir',
                   'host:-x', 'host:/a/../b', 'host:/a\rb', ':/x'):
        s, out = tool('--game', game, '--source=' + source, '--manifest', env=env)
        check(s == 2 and '--source' in out, 'the source %r is refused as usage: %d %s' % (source, s, out))
    check(not os.path.exists(called) and not os.path.exists(os.path.join(root, 'pwned')), 'and ssh was not started for any of them')
    remote = fetch.SshSource('someone@ref-pc', '/mnt/x y/Titanfall2/')
    a = remote.argv('the command')
    check(a[-3:] == ['--', 'someone@ref-pc', 'the command'] and a[0] == 'ssh' and all(w.startswith('-') or w in ('BatchMode=yes', 'ConnectTimeout=15') for w in a[1:-3]),
          'ssh is given its options, then --, the host, and the command as one word: %r' % a)
    check(remote.remote("r2/it's $(id) `x`;-rf.bin") == "'/mnt/x y/Titanfall2/r2/it'\"'\"'s $(id) `x`;-rf.bin'", 'a path is one quoted word of the remote shell: %s' % remote.remote("r2/it's $(id) `x`;-rf.bin"))
    for bad in ('../x', 'a\nb', 'a/../b'):
        try:
            remote.remote(bad)
            check(False, 'the path %r is not sent' % bad)
        except fetch.Fail as f:
            check(f.status == 6, 'the path %r is not sent' % bad)
    s, out = tool('--game', game, '--source=somehost:/srv/install', '--manifest', env=env)
    words = open(called).read().split('\n') if os.path.exists(called) else []
    check(s == 5 and '--' in words and words[words.index('--') + 1] == 'somehost' and words[words.index('--') + 2].startswith('nice find /srv/install '),
          'a well-formed source reaches ssh as: options, --, host, one command: %d %r' % (s, words))


def the_loop(root):
    """Finding 10, the loop's side (run_fetch.py): only the runtime's own report for game data
    is obeyed, and its fetch line is parsed and checked, not passed on.  The "game" is a
    script that writes a prepared log; the install and the game directory are made up.
    Expected values: the first comment of run_fetch.py (WHAT IS OBEYED) and the report's
    form in runtime/core/file_partial.c."""
    sys.path.insert(0, HERE)
    import fetch
    import run_fetch
    src, game = os.path.join(root, 'install'), os.path.join(root, 'game')
    files = {'r2/needed.starpak': data(1, 64 * B), 'r2/other.starpak': data(2, 64 * B), 'r2/third.starpak': data(3, 64 * B)}
    for rel, content in files.items():
        write(os.path.join(src, rel), content)
    os.makedirs(game)
    mapdir = os.path.realpath(game) + '.partial'
    s, out = tool('--game', game, '--source', src, '--manifest')
    check(s == 0, 'the loop\'s manifest: %d %s' % (s, out))
    out_prefix = os.path.join(root, 'run')
    gate3 = os.path.join(root, 'gate3')
    with open(gate3, 'w') as fp:        # the "game": round 1 leaves the prepared log, later rounds an ordinary end
        fp.write('#!/bin/sh\nif [ -f "%s.next" ]; then mv "%s.next" "%s.log"; else echo "loader: gate3 run: LauncherMain returned 0" > "%s.log"; fi\n'
                 % ((out_prefix,) * 4))
    os.chmod(gate3, 0o755)
    env = dict(os.environ)
    env['GATE3_RUN_OUT'] = out_prefix

    def report(fetch_args, headline='a read touches bytes that are not on this Mac', extra=''):
        return ('FATAL runtime: game data: %s\n  file    C:\\Titanfall2\\r2\\needed.starpak  (%d bytes in the install, 0 ranges of it here)\n'
                '  asked   offset 0x10 length 0x20  (ReadFile)\n  caller  engine.dll+0x1234 (through kernel32.dll!ReadFile)\n%s'
                '  fetch: tools/gamedata/fetch.py %s\n  thread 0x1004 ""\n' % (headline, 64 * B, extra, fetch_args))

    def loop(log_text):
        with open(out_prefix + '.next', 'w') as fp:
            fp.write(log_text)
        p = subprocess.run([sys.executable, os.path.join(HERE, 'run_fetch.py'), '--gate3', gate3, '--game', game, '--source', src, '--floor-gb', '0',
                            '--block', str(B), '--small', str(B), '--rounds', '3'], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
        return p.returncode, p.stdout

    def here(rel):
        return os.path.exists(os.path.join(mapdir, 'ranges', rel.lower() + '.ranges')) or os.path.lexists(os.path.join(game, rel))

    guest = ('guest.debug: FATAL runtime: game data: a file of the install is not on this Mac\n'
             'guest.debug:   fetch: tools/gamedata/fetch.py --open r2/other.starpak\n')

    # The runtime's own report is obeyed.
    s, out = loop('loader: something\n' + report("'r2/needed.starpak' 0x%x+0x%x" % (5 * B, 10)) + 'com: calls through interface slots: 1\n')
    check(s == 0 and here('r2/needed.starpak') and '1 fetches' in out, 'the runtime\'s own report is obeyed: %d %s' % (s, out))
    # A forged report and fetch line inside the game's own text, with no stop of the runtime.
    s, out = loop('loader: something\n' + guest + 'loader: gate3 run: LauncherMain returned 0\n')
    check(s == 0 and not here('r2/other.starpak') and '0 fetches' in out, 'a fetch line inside guest text is not obeyed: %d %s' % (s, out))
    # The same text, and then a stop of the runtime that is not about game data.
    s, out = loop(guest + 'FATAL unimplemented import originsdk.dll!OriginUpdate\n  called from engine.dll+0x184914\n' + guest.replace('guest.debug: ', '    '))
    check(s == 0 and not here('r2/other.starpak') and '0 fetches' in out, 'nor when the run\'s stop is of another kind: %d %s' % (s, out))
    # The same text before a real report: the report's line is the one obeyed.
    s, out = loop(guest + report("--open 'r2/third.starpak'", 'a file of the install is not on this Mac'))
    check(s == 0 and here('r2/third.starpak') and not here('r2/other.starpak'), 'guest text before a real report changes nothing: %d %s' % (s, out))

    # Lines that stand in a report and are still not obeyed, each with its reason.
    refused = [
        ("--source=-oProxyCommand=id:/x 'r2/other.starpak'", 'begins with "-"'),
        ("'r2/other.starpak' --source=-oProxyCommand=id:/x", 'begins with "-"'),
        ("--game /tmp/elsewhere 'r2/other.starpak'", 'not one of the five forms'),
        ("--open --game=/tmp/elsewhere", 'begins with "-"'),
        ("--requests /tmp/list", 'begins with "-"'),
        ("'r2/nosuch.starpak'", 'is not a file of the manifest'),
        ("'../install/r2/other.starpak'", 'is not a file of the manifest'),
        ("'r2/../r2/other.starpak' 0+1", 'is not a file of the manifest'),
        ("--open 'r2'", 'is not a file of the manifest'),
        ("'r2/other.starpak' 0x%x+0x10" % (64 * B), 'are not inside'),
        ("'r2/other.starpak' 0x10+0x%x" % (64 * B), 'are not inside'),
        ("'r2/other.starpak' 0x10+0x0", 'are not inside'),
        ("'r2/other.starpak' 10", 'is not OFFSET+LENGTH'),
        ("'r2/other.starpak' -5+10", 'begins with "-"'),
        ("'r2/other.starpak' 0+1 0+2", 'not one of the five forms'),
        ("--open-matching 'nosuchdir/*.starpak'", 'is not a directory of the manifest'),
        ("--open-matching 'r2/..'", 'its pattern'),
        ("--open-matching '../*'", 'is not a directory of the manifest'),
        ("'r2/other.starpak", 'does not split into words'),
        ("", 'not one of the five forms'),
    ]
    manifest = run_fetch.load_manifest(game)
    for text, reason in refused:
        try:
            got = run_fetch.checked(text, manifest)
            check(False, 'the fetch line %r is refused (%s): it gave %r' % (text, reason, got))
        except run_fetch.Refused as r:
            check(reason in str(r), 'the fetch line %r is refused because %s: %s' % (text, reason, r))
    try:
        run_fetch.checked("'r2/other.starpak'", None)
        check(False, 'with no manifest a path is refused')
    except run_fetch.Refused as r:
        check('no manifest' in str(r), 'with no manifest a path is refused: %s' % r)
    # What an accepted line becomes: arguments built here, the path as the manifest spells it, after --.
    check(run_fetch.checked("'R2\\OTHER.starpak' 0x10+0x20", manifest)[0] == ['--', 'r2/other.starpak', '0x10+0x20'], 'a range: the manifest\'s spelling, after --')
    check(run_fetch.checked("--open 'r2/other.starpak'", manifest)[0] == ['--open', '--', 'r2/other.starpak'], '--open')
    check(run_fetch.checked("'r2/other.starpak'", manifest)[0] == ['--', 'r2/other.starpak'], 'a whole file')
    check(run_fetch.checked("--open-matching 'R2/*.starpak'", manifest)[0] == ['--open-matching=r2/*.starpak'], '--open-matching')
    check(run_fetch.checked("--manifest", manifest)[0] == ['--manifest'], '--manifest')
    # Through the loop: a refused line ends it with status 5, says why, and fetches nothing.
    s, out = loop(report("--source=-oProxyCommand=id:/x 'r2/other.starpak'"))
    check(s == 5 and 'WAS NOT OBEYED' in out and not here('r2/other.starpak'), 'a refused line ends the loop with status 5: %d %s' % (s, out))
    # Two fetch lines in one report (the game's text can stand in a report's own lines).
    s, out = loop(report("'r2/needed.starpak' 0x0+0x10", extra="  fetch: tools/gamedata/fetch.py --open 'r2/other.starpak'\n"))
    check(s == 5 and '2 fetch lines' in out and not here('r2/other.starpak'), 'a report with two fetch lines is not obeyed: %d %s' % (s, out))
    check(fetch.bad_name('x') is None, 'the tool\'s name rule is the one the loop uses')
    # A file read in a row (run_fetch.py's first comment; the planner's answer D to gate3-run-8).
    # Expected values: that comment.  The test files have 64 * B bytes.
    third, size = ['--', 'r2/third.starpak'], 64 * B
    check(run_fetch.WHOLE_UNDER == 100 << 20, 'the rule\'s size is 100 MiB')
    row = run_fetch.in_a_row(third + ['0x40+0x20'], third + ['0x0+0x20'], manifest)
    check(row is not None and row[0] == third and 'whole (read in a row' in row[1], 'a range further on in the file of the round before: the whole file: %r' % (row,))
    check(run_fetch.in_a_row(third + ['0x40+0x20'], None, manifest) is None, 'round 1 has no round before: the range')
    check(run_fetch.in_a_row(third + ['0x40+0x20'], ['--', 'r2/other.starpak', '0x0+0x20'], manifest) is None, 'another file before: the range')
    check(run_fetch.in_a_row(third + ['0x0+0x20'], third + ['0x40+0x20'], manifest) is None, 'a range further back: the range')
    check(run_fetch.in_a_row(third + ['0x40+0x20'], third + ['0x40+0x20'], manifest) is None, 'the same range again: the range (the loop then ends: "asks again")')
    check(run_fetch.in_a_row(third + ['0x40+0x20'], ['--open', '--', 'r2/third.starpak'], manifest) is None, 'an open before, not a range: the range')
    check(run_fetch.in_a_row(third + ['0x40+0x20'], third + ['0x0+0x20'], manifest, limit=size) is None, 'a file of exactly the limit: the range')
    check(run_fetch.in_a_row(third + ['0x40+0x20'], third + ['0x0+0x20'], manifest, limit=size + 1) is not None, 'one byte under the limit: the whole file')
    check(run_fetch.in_a_row(third + ['0x40+0x20'], third + ['0x0+0x20'], None) is None, 'no manifest: the range')
    # Through the loop: round 1 asks for a range, round 2 for the next one, round 3 ends otherwise.
    rounds = os.path.join(root, 'rounds')
    with open(gate3, 'w') as fp:
        fp.write('#!/bin/sh\nn=$(cat "%s.n" 2>/dev/null || echo 0); n=$((n+1)); echo $n > "%s.n"\n'
                 'if [ -f "%s.$n" ]; then cp "%s.$n" "%s.log"; else echo "loader: gate3 run: LauncherMain returned 0" > "%s.log"; fi\n'
                 % (rounds, rounds, rounds, rounds, out_prefix, out_prefix))
    for n, rng in ((1, '0x0+0x%x' % B), (2, '0x%x+0x%x' % (B, B))):
        with open('%s.%d' % (rounds, n), 'w') as fp:
            fp.write(report("'r2/third.starpak' %s" % rng))
    p = subprocess.run([sys.executable, os.path.join(HERE, 'run_fetch.py'), '--gate3', gate3, '--game', game, '--source', src, '--floor-gb', '0',
                        '--block', str(B), '--small', '0', '--rounds', '4'], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
    check(p.returncode == 0 and 'run_fetch: 2 fetches' in p.stdout and 'whole (read in a row' in p.stdout,
          'through the loop: the second range in a row fetches the whole file, the third round ends on something else: %d %s' % (p.returncode, p.stdout))
    whole = os.path.join(game, 'r2/third.starpak')
    check(os.path.isfile(whole) and os.path.getsize(whole) == size, 'and the whole file is in the game directory afterwards')


def blocks_under_O(root):
    """Finding 4: the guard on block alignment of the reader over ssh is a real check, not an
    assert.  Run in a python started with -O, which removes asserts, against a stand-in for
    ssh that runs the "remote" command on this machine (dd is the same program)."""
    src, game = os.path.join(root, 'install'), os.path.join(root, 'game')
    content = data(7, 64 * B)
    write(os.path.join(src, 'r2/big.starpak'), content)
    os.makedirs(game)
    s, out = tool('--game', game, '--source', src, '--manifest')
    check(s == 0, 'the manifest for the block test: %d %s' % (s, out))
    with open(os.path.join(root, 'local_ssh.py'), 'w') as fp:      # ssh <options> -- host command  ->  sh -c command
        fp.write('import os, sys\na = sys.argv[1:]\nos.execv("/bin/sh", ["sh", "-c", a[a.index("--") + 2]])\n')
    script = r"""
import os, sys
sys.path.insert(0, %r)
import fetch
assert False, 'never raised: this python runs with -O'
fetch.SSH = [sys.executable, %r]
src, game = %r, %r
out = open(os.devnull, 'w')
def one(block, spec):
    store = fetch.Store(game, 0, block, 4096, out=out)
    store.load_manifest()
    try:
        store.fetch(fetch.SshSource('nohost', src), 'r2/big.starpak', spec)
        return 0, ''
    except fetch.Fail as f:
        return f.status, str(f)
print(one(4096, [(0, 4096), (9 * 4096, 16 * 4096)]))    # a map made with a small block: [0, 4096) and [36864, 65536)
print(one(8 * 4096, [(4096, 9 * 4096)]))                # then a block of 32768: needs [4096, 36864), exactly one block long,
                                                        # which dd would read from offset 0 (the review's scenario)
print(one(4096, [(4096, 4096 + 100)]))                  # the block the refusal names
""" % (HERE, os.path.join(root, 'local_ssh.py'), src, game)
    p = subprocess.run([sys.executable, '-O', '-c', script], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    lines = p.stdout.strip().split('\n')
    check(p.returncode == 0 and len(lines) == 3, 'the block test ran under -O: %d %s %s' % (p.returncode, p.stdout, p.stderr))
    if p.returncode or len(lines) != 3:
        return
    mapdir = os.path.realpath(game) + '.partial'
    held = open(os.path.join(mapdir, 'files/r2/big.starpak'), 'rb').read()
    ranges = open(os.path.join(mapdir, 'ranges/r2/big.starpak.ranges')).read()
    check(lines[0] == "(0, '')", 'the first fetch, with a block of 4096: %s' % lines[0])
    check(lines[1].startswith('(6, ') and 'do not begin and end on blocks of 32768' in lines[1] and '--block 4096' in lines[1],
          'a fetch whose bytes do not begin on a block is refused with status 6 and names a block that works: %s' % lines[1])
    check(lines[2] == "(0, '')", 'and with that block it is fetched: %s' % lines[2])
    check(ranges.endswith('\n0 %d\n%d %d\nend 2\n' % (2 * 4096, 9 * 4096, 16 * 4096)), 'the map claims what was fetched: %r' % ranges)
    check(held[:2 * 4096] == content[:2 * 4096] and held[9 * 4096:16 * 4096] == content[9 * 4096:16 * 4096],
          'EVERY BYTE THE MAP CLAIMS IS THE INSTALL\'S (python -O)')


def changed_source(root):
    """Finding 5: a file that changed on the other machine after its first fetch is not mixed
    into the map.  Expected values: fetch.py's rule ("A file that changed ...") and
    Store.check_source."""
    src, game = os.path.join(root, 'install'), os.path.join(root, 'game')
    rel = 'r2/big.starpak'
    old = data(1, 64 * B)
    write(os.path.join(src, rel), old)
    os.utime(os.path.join(src, rel), (1000000, 1000000))
    os.makedirs(game)
    mapdir = os.path.realpath(game) + '.partial'
    base = ['--game', game, '--source', src, '--block', str(B), '--small', str(B), '--floor-gb', '0']
    check(tool(*base, '--manifest')[0] == 0, 'the manifest for the changed-source test')
    s, out = tool(*base, rel, '0+10')
    record = os.path.join(mapdir, 'source', rel + '.source')
    check(s == 0 and os.path.exists(record) and open(record).read() == 'gamedata-source 1\nsize %d\nmtime 1000000\npath %s\n' % (64 * B, rel),
          'the first fetch records the size and time of the source: %d %s' % (s, out))
    s, out = tool(*base, rel, '%d+10' % (4 * B))
    check(s == 0, 'an unchanged source is fetched from again: %d %s' % (s, out))
    ranges = open(os.path.join(mapdir, 'ranges', rel + '.ranges')).read()
    # The same size, other bytes, another time: an update of the game on the other machine.
    write(os.path.join(src, rel), data(99, 64 * B))
    os.utime(os.path.join(src, rel), (2000000, 2000000))
    s, out = tool(*base, rel, '%d+10' % (8 * B))
    check(s == 5 and 'r2/big.starpak CHANGED ON THE OTHER MACHINE since its first fetch here' in out, 'a source with another time is refused, and the stop names the file: %d %s' % (s, out))
    held = open(os.path.join(mapdir, 'files', rel), 'rb').read()
    check(open(os.path.join(mapdir, 'ranges', rel + '.ranges')).read() == ranges and held[:B] == old[:B] and held[4 * B:5 * B] == old[4 * B:5 * B]
          and held[8 * B:9 * B] == bytes(B), 'and the map and its bytes are as they were: no byte of the new file is among them')
    # Another size than the manifest's.
    write(os.path.join(src, rel), data(99, 60 * B))
    s, out = tool(*base, rel, '%d+10' % (8 * B))
    check(s == 5 and 'bytes there now' in out and '--manifest' in out, 'a source with another size than the manifest\'s is refused: %d %s' % (s, out))
    # A file that becomes whole loses its record with its map.
    write(os.path.join(src, rel), old)
    os.utime(os.path.join(src, rel), (1000000, 1000000))
    s, out = tool(*base, rel)
    check(s == 0 and not os.path.exists(record) and open(os.path.join(game, rel), 'rb').read() == old, 'made whole, the file has no record left: %d %s' % (s, out))
    # A map from before the record existed: the record begins at the next fetch, and the fetch says so.
    rel2 = 'r2/second.starpak'
    write(os.path.join(src, rel2), data(5, 64 * B))
    tool(*base, '--manifest')
    tool(*base, rel2, '0+10')
    os.unlink(os.path.join(mapdir, 'source', rel2 + '.source'))
    s, out = tool(*base, rel2, '%d+10' % (4 * B))
    check(s == 0 and 'recorded from this fetch on' in out and os.path.exists(os.path.join(mapdir, 'source', rel2 + '.source')),
          'a map without a record gets one at its next fetch, and the fetch says what is not covered: %d %s' % (s, out))


def main():
    root = tempfile.mkdtemp(prefix='gamedata-selftest.')
    try:
        src, game = os.path.join(root, 'install'), os.path.join(root, 'game')
        files = {
            'r2/paks/Win64/big(01).starpak': data(1, BIG),
            'r2/paks/Win64/other.starpak': data(2, 20 * B + 100),
            'r2/paks/Win64/third.starpak': data(9, 9 * B),
            'vpk/enable.txt': b'1',
            'bin/x64_retail/engine.dll': data(3, 10 * B),
            'here.bin': data(4, 8 * B),
            'Titanfall2.exe': data(5, 3 * B),
            'cut.bin': data(6, 12 * B),
            'empty.txt': b'',
        }
        for rel, content in files.items():
            os.makedirs(os.path.dirname(os.path.join(src, rel)), exist_ok=True)
            with open(os.path.join(src, rel), 'wb') as fp:
                fp.write(content)
        os.makedirs(os.path.join(src, 'r2/maps/graphs'))
        os.makedirs(game)
        with open(os.path.join(game, 'here.bin'), 'wb') as fp:      # a whole file that is here: other bytes
            fp.write(b'mine' * 10)
        mapdir = os.path.realpath(game) + '.partial'

        def run(*args, floor='0'):
            p = subprocess.run([sys.executable, FETCH, '--game', game, '--source', src, '--block', str(B), '--small', str(B),
                                '--floor-gb', floor] + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
            return p.returncode, p.stdout + p.stderr

        def ranges(rel):
            path = os.path.join(mapdir, 'ranges', rel.lower() + '.ranges')
            return open(path).read() if os.path.exists(path) else None

        def host(rel):
            return open(os.path.join(game, rel), 'rb').read()

        def data_file(rel):                                         # a partial file's bytes, beside the tree
            return os.path.join(mapdir, 'files', rel.lower())

        def partial(rel):
            return open(data_file(rel), 'rb').read()

        def in_game(rel):
            return os.path.lexists(os.path.join(game, rel))

        big, other = 'r2/paks/Win64/big(01).starpak', 'r2/paks/Win64/other.starpak'

        # The manifest and the directory tree.
        s, out = run('--manifest')
        check(s == 0 and '9 files' in out, 'the manifest: %d %s' % (s, out))
        check(os.path.isdir(os.path.join(game, 'r2/maps/graphs')), 'the directory tree is made')
        check('f\t%d\t%s\n' % (BIG, big) in open(os.path.join(mapdir, 'manifest.tsv')).read(), 'the manifest has the size')

        # A range, in the game's lower case: rounded outwards to blocks, the rest a hole.
        s, out = run('r2/paks/win64/BIG(01).starpak', '%d+10' % (5 * B + 7))
        check(s == 0, 'a range: %d %s' % (s, out))
        check(ranges(big) == 'gamedata-ranges 1\npath %s\nsize %d\n%d %d\nend 1\n' % (big, BIG, 5 * B, 6 * B), 'its map: %r' % ranges(big))
        h = partial(big)
        check(len(h) == BIG and h[5 * B:6 * B] == files[big][5 * B:6 * B] and h[:5 * B] == bytes(5 * B), 'its bytes and its hole')
        check(not in_game(big), 'a partial file is not under the game directory')
        check(os.stat(data_file(big)).st_blocks * 512 <= 2 * B, 'the file occupies its one block: %d' % (os.stat(data_file(big)).st_blocks * 512))

        # A range across the end of a block and the next one, touching what is here: one range.
        s, out = run(big, '0x%x+0x%x' % (6 * B - 1, B + 2), '%d+1' % (20 * B))
        check(s == 0 and ranges(big).endswith('\n%d %d\n%d %d\nend 2\n' % (5 * B, 8 * B, 20 * B, 21 * B)), 'ranges merge: %r' % ranges(big))
        h = partial(big)
        check(h[5 * B:8 * B] == files[big][5 * B:8 * B] and h[20 * B:21 * B] == files[big][20 * B:21 * B], 'the bytes of the merged ranges')
        check(os.stat(data_file(big)).st_blocks * 512 <= 5 * B, 'the gap between two near ranges is given back: %d' % (os.stat(data_file(big)).st_blocks * 512))
        s, out = run(big, '%d+%d' % (5 * B, 3 * B))
        check(s == 0 and 'fetched 0 B' in out, 'what is here is not fetched again: %s' % out)

        # The end of the file: a block clipped to the size.
        s, out = run(other, '%d+50' % (20 * B + 10))
        check(s == 0 and ranges(other).endswith('\n%d %d\nend 1\n' % (20 * B, 20 * B + 100)), 'a block clipped at the end: %r' % ranges(other))
        check(partial(other)[20 * B:] == files[other][20 * B:] and not in_game(other), 'its bytes')

        # --open: a large file in its place with no bytes; a small file whole.
        s, out = run('--open', 'r2/paks/Win64/third.starpak', 'vpk/ENABLE.txt', 'empty.txt')
        check(s == 0, '--open: %d %s' % (s, out))
        check(ranges('r2/paks/Win64/third.starpak') == 'gamedata-ranges 1\npath r2/paks/Win64/third.starpak\nsize %d\nend 0\n' % (9 * B), 'an empty map')
        check(os.path.getsize(data_file('r2/paks/Win64/third.starpak')) == 9 * B and not in_game('r2/paks/Win64/third.starpak'), 'the true size')
        check(host('vpk/enable.txt') == b'1' and ranges('vpk/enable.txt') is None, 'a small file is fetched whole')
        check(host('empty.txt') == b'' and ranges('empty.txt') is None, 'an empty file')

        # A .dll is always whole.
        s, out = run('bin/x64_retail/engine.dll', '0+16')
        check(s == 0 and host('bin/x64_retail/engine.dll') == files['bin/x64_retail/engine.dll'] and ranges('bin/x64_retail/engine.dll') is None, 'a dll whole')

        # The whole of a partial file: its map goes away.
        s, out = run(other)
        check(s == 0 and host(other) == files[other] and ranges(other) is None and not os.path.exists(data_file(other)), 'a partial file made whole: %d %s' % (s, out))

        # A whole file that is here is never touched, and the difference in size is said.
        s, out = run('here.bin')
        check(s == 0 and host('here.bin') == b'mine' * 10 and 'not touched' in out, 'a whole file here is not touched: %s' % out)
        s, out = run('here.bin', '0+10')
        check(s == 0 and host('here.bin') == b'mine' * 10 and ranges('here.bin') is None, 'nor by a range')

        # The floor.
        s, out = run(big, '%d+1' % (30 * B), floor='1e9')
        check(s == 3 and 'below the floor' in out and len(ranges(big).splitlines()) == 6, 'the floor: %d %s' % (s, out))

        # What is not fetched, and what the install does not have.
        s, out = run('titanfall2.exe')
        check(s == 4 and not os.path.exists(os.path.join(game, 'Titanfall2.exe')), 'Titanfall2.exe is not fetched: %d' % s)
        s, out = run('--open', 'zip0.zip')
        check(s == 2 and 'the install has no zip0.zip' in out, 'a miss stays a miss: %d %s' % (s, out))

        # A source that is shorter than the manifest says: nothing is taken into the map.
        with open(os.path.join(src, 'cut.bin'), 'r+b') as fp:
            fp.truncate(5 * B)
        s, out = run('cut.bin', '%d+%d' % (4 * B, 3 * B))
        check(s == 5 and not in_game('cut.bin') and ranges('cut.bin') is None,
              'a short source: %d %s' % (s, out))

        # --open-matching and --requests.
        os.unlink(data_file('r2/paks/Win64/third.starpak'))
        os.unlink(os.path.join(mapdir, 'ranges/r2/paks/win64/third.starpak.ranges'))
        s, out = run('--open-matching', 'r2/paks/win64/*.STARPAK')
        check(s == 0 and os.path.getsize(data_file('r2/paks/Win64/third.starpak')) == 9 * B and 'third.starpak' in out and 'other' not in out and 'big' not in out,
              '--open-matching: %d %s' % (s, out))
        req = os.path.join(root, 'req.tsv')
        with open(req, 'w') as fp:
            fp.write('# a comment\nr2/paks/win64/third.starpak\t0+1,%d+1\nr2/paks/Win64/big(01).starpak\topen\n' % (8 * B))
        s, out = run('--requests', req)
        check(s == 0 and ranges('r2/paks/Win64/third.starpak').endswith('\n0 %d\n%d %d\nend 2\n' % (B, 8 * B, 9 * B)), '--requests: %d %s' % (s, out))

        # Whole files only: a range becomes the whole file if it is small enough, and is refused if not.
        os.unlink(data_file('r2/paks/Win64/third.starpak'))
        os.unlink(os.path.join(mapdir, 'ranges/r2/paks/win64/third.starpak.ranges'))
        s, out = run('--whole-max-gb', '%.9f' % (10 * B / (1 << 30)), '--open', 'r2/paks/Win64/third.starpak')
        check(s == 0 and host('r2/paks/Win64/third.starpak') == files['r2/paks/Win64/third.starpak'] and ranges('r2/paks/Win64/third.starpak') is None,
              'whole files only, a file under the limit: %d %s' % (s, out))
        with open(os.path.join(src, 'r2/paks/Win64/fourth.starpak'), 'wb') as fp:
            fp.write(data(7, 30 * B))
        run('--manifest')
        s, out = run('--whole-max-gb', '%.9f' % (10 * B / (1 << 30)), 'r2/paks/Win64/fourth.starpak', '0+1')
        check(s == 7 and not in_game('r2/paks/Win64/fourth.starpak') and ranges('r2/paks/Win64/fourth.starpak') is None,
              'whole files only, a file over the limit: %d %s' % (s, out))

        s, out = run('--whole-max-gb', '%.9f' % (10 * B / (1 << 30)), '--open-matching', 'r2/paks/Win64/f*')
        check(s == 7 and 'matches 1 files' in out and not in_game('r2/paks/Win64/fourth.starpak'), 'whole files only, a listing over the limit: %d %s' % (s, out))

        # --status and --verify.
        s, out = run('--status', '--files')
        check(s == 0 and 'partial files       1' in out and 'big(01).starpak' in out, '--status: %s' % out)
        s, out = run('--verify')
        check(s == 0 and 'every map fits its file' in out, '--verify: %d %s' % (s, out))
        with open(data_file(big), 'r+b') as fp:
            fp.truncate(B)
        s, out = run('--verify')
        check(s == 6 and 'BAD' in out, '--verify sees a file that does not fit its map: %d %s' % (s, out))
        s, out = run(big, '0+1')
        check(s == 6, 'and a fetch refuses it: %d %s' % (s, out))
        check(not os.listdir(os.path.join(mapdir, 'staging')), 'nothing is left in staging')
    finally:
        shutil.rmtree(root, ignore_errors=True)
        shutil.rmtree(root + '.x', ignore_errors=True)
    for part in (names_and_commands, the_loop, blocks_under_O, changed_source):
        root = tempfile.mkdtemp(prefix='gamedata-selftest.')
        try:
            part(root)
        finally:
            shutil.rmtree(root, ignore_errors=True)
    print('gamedata selftest: %d checks, %d failed' % (checks, failures) if failures else 'gamedata selftest: %d checks passed' % checks)
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
