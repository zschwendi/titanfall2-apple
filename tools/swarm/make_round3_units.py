def main():
    if "--list" in sys.argv:
        for uid, title, kind, issue, prio, needs, _ in UNITS:
            print(f"{uid:24} {kind:12} #{issue:<3} p{prio} needs={','.join(needs) or '-'}  {title}")
        return 0
    wrote = 0
    for uid, title, kind, issue, prio, needs, check in UNITS:
        brief = os.path.join(ROOT, "swarm", "briefs", uid + ".md")
        if not os.path.exists(brief):
            print(f"{uid}: no brief at swarm/briefs/{uid}.md, not written", file=sys.stderr)
            return 1
        path = os.path.join(ROOT, "swarm", "units", uid + ".json")
        if os.path.exists(path):
            continue
        unit = {"id": uid, "title": title, "kind": kind, "issue": issue, "model": "opus",
                "priority": prio, "needs": needs, "check": check, "state": "todo",
                "attempts": 0, "history": []}
        with open(path, "w") as f:
            json.dump(unit, f, indent=2, sort_keys=True)
            f.write("\n")
        wrote += 1
        print("wrote", os.path.relpath(path, ROOT))
    print(f"{wrote} unit file(s) written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
