#!/usr/bin/env python3
"""Write the external imports of the 24 game DLLs as a machine-readable list.

Reads inventory/inventory.json with the tables of tools/scout/import_surface.py, which is
imported as a module so the tables live in one place.  Writes to stdout one row per distinct
(library, import) of list (b) of docs/findings/24-import-surface.md:

    library  name  ordinal  wave  mark

with '#' comment lines before the rows.  The result is runtime/tools/imports.def, regenerated by

    .venv/bin/python runtime/tools/gen_imports.py inventory/inventory.json > runtime/tools/imports.def

Exits non-zero, with a message on stderr, if the tables and the inventory disagree or if the
rows fail their own checks.  Standard library only; writes nothing but stdout.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools", "scout"))
sys.dont_write_bytecode = True          # no __pycache__ left in tools/scout
import import_surface as S              # noqa: E402


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_imports.py inventory/inventory.json")
    _, game, own, shipped = S.load(sys.argv[1])
    ext_b = S.external(game, own)
    ext_a = S.external([f for f in game if f["file"] in S.SET_A], own)
    S.classify(ext_b)                   # exits if the tables and the inventory disagree
    mk = S.marks(ext_b, shipped)
    wave_of = {name: number for number, _, _, text in S.WAVES for name in S.words(text)}
    total_a = sum(len(v) for v in ext_a.values())
    if sum(len(S.words(text)) for _, _, _, text in S.WAVES) != len(wave_of):
        sys.exit("the wave table lists a name twice")

    rows = []
    for lib in sorted(ext_b):
        for name in sorted(ext_b[lib], key=S.sort_key):
            if name.startswith("#"):
                number = int(name[1:])
                label = S.ORDINALS.get(lib, {}).get(number)
                if label is None:
                    sys.exit("ordinal import %s!%s has no published name in S.ORDINALS" % (lib, name))
                ordinal = str(number)
            else:
                label, ordinal = name, "-"
            wave = "-"
            if name in ext_a.get(lib, {}):
                if name not in wave_of:
                    sys.exit("%s!%s is in list (a) but not in the wave table" % (lib, name))
                wave = str(wave_of[name])
            rows.append((lib, label, ordinal, wave, mk[(lib, name)] or "-"))

    # Self-checks.
    seen_names, seen_ords = set(), set()
    for row in rows:
        if any(len(field.split()) != 1 for field in row):
            sys.exit("row %s has an empty field or a space inside a field" % " ".join(row))
        if (row[0], row[1]) in seen_names:
            sys.exit("%s %s appears twice" % (row[0], row[1]))
        seen_names.add((row[0], row[1]))
        if row[2] != "-" and (row[0], row[2]) in seen_ords:
            sys.exit("%s ordinal %s appears twice" % (row[0], row[2]))
        if row[2] != "-":
            seen_ords.add((row[0], row[2]))
    with_wave = sum(1 for row in rows if row[3] != "-")
    if with_wave != total_a:
        sys.exit("%d rows have a wave but list (a) has %d imports" % (with_wave, total_a))

    def pad(text, width):               # a longer field (mangled C++ names) keeps two spaces
        return text + " " * max(2, width - len(text))

    lines = [
        "# The external imports of the %d game DLLs: list (b) of docs/findings/24-import-surface.md." % len(game),
        "#",
        "# GENERATED by runtime/tools/gen_imports.py from inventory/inventory.json with the tables of",
        "# tools/scout/import_surface.py.  Do not edit.  To regenerate:",
        "#",
        "#     .venv/bin/python runtime/tools/gen_imports.py inventory/inventory.json > runtime/tools/imports.def",
        "#",
        "# Read by runtime/tools/check_shim.py: a shim must implement a function listed here (or in",
        "# runtime/tools/imports_extra.def, which the planner maintains by hand).",
        "#",
        "# Columns: library, function name, ordinal (- if imported by name; for an import by ordinal the",
        "# name is the published one), wave of list (a) (1-6, - if the function is not in list (a)),",
        "# mark (letters of finding 24: T tool or debug path, U looks unused in single-player, O only",
        "# OriginSDK.dll imports it, S only the stubbed GFSDK DLLs import it, N delay-loaded from a DLL",
        "# the install does not contain; - if none).",
        "#",
        "# %d imports from %d libraries; %d are in list (a)." % (len(rows), len(ext_b), total_a),
    ]
    for lib, label, ordinal, wave, mark in rows:
        lines.append(pad(lib, 16) + pad(label, 44) + pad(ordinal, 8) + pad(wave, 6) + mark)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
