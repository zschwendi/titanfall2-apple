#!/usr/bin/env python3
"""Write runtime/core/bestfit1252.inc from Microsoft's best-fit table of code page 1252.

    python3 -I runtime/tools/gen_bestfit.py path/to/bestfit1252.txt > runtime/core/bestfit1252.inc

The source file is published by the Unicode Consortium at
https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WindowsBestFit/bestfit1252.txt and is not
kept in this repository.  Its WCTABLE section lists, for 698 UTF-16 code units, the byte that
WideCharToMultiByte(1252, 0, ...) produces.  256 of them are the page's own characters (the
MBTABLE section read backwards), which runtime/core/locale.c already has; the others are the
best-fit substitutions and are what this writes, sorted by code unit.
"""
import re
import sys


def main():
    mb, wc, sect = {}, {}, None
    for raw in open(sys.argv[1], "rb").read().decode("latin-1").splitlines():
        line = raw.split(";")[0].strip()
        if line.startswith("MBTABLE"):
            sect = mb
        elif line.startswith("WCTABLE"):
            sect = wc
        elif line.startswith("ENDCODEPAGE"):
            sect = None
        else:
            m = re.fullmatch(r"0x([0-9a-fA-F]+)\s+0x([0-9a-fA-F]+)", line)
            if m and sect is not None:
                sect[int(m.group(1), 16)] = int(m.group(2), 16)
    if len(mb) != 256 or len(wc) < 256:
        sys.exit("gen_bestfit: this does not look like bestfit1252.txt (%d and %d entries)" % (len(mb), len(wc)))
    best = sorted((u, b) for u, b in wc.items() if mb.get(b) != u)
    print("/* Generated by runtime/tools/gen_bestfit.py from Microsoft's bestfit1252.txt (WCTABLE without")
    print(" * the page's own 256 characters): %d best-fit substitutions of WideCharToMultiByte for code" % len(best))
    print(" * page 1252, sorted by code unit.  Do not edit; regenerate. */")
    for i in range(0, len(best), 6):
        print("    " + " ".join("{0x%04X, 0x%02X}," % p for p in best[i:i + 6]))


if __name__ == "__main__":
    main()
