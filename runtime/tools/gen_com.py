#!/usr/bin/env python3
"""Generate vtable thunks and tables for the interface layer (docs/RUNTIME.md section 3.7;
runtime/include/rt/com.h; docs/handoff/d3d-interface-layer.md).

Reads every <desc dir>/<Interface>.idef (the format: runtime/com/gen_desc.py), the accept
list, and the body files <bodies dir>/<Interface>/<Method>.c, and writes into the output
directory:

    <prefix>_types.h     the C names of the types whose rows in a types file end in `#= ...`
                         (enumerations as uint32_t, typedefs, incomplete structs)
    <prefix>_ids.h       per interface: extern RtComIface rt_iface_<I>, its method and count
                         arrays, RT_COM_SLOT_<I>_<M>
    <prefix>_thunks.c    one thunk per (interface, slot)
    <prefix>_table.c     the method rows, the interfaces, the RtComTable
    <prefix>_calls.h     typed wrappers behind COM_CALL() for tests: call a method through
                         the object's vtable and the guest ABI

WHAT A THUNK DOES is decided here, per (interface, method), in this order:
    QueryInterface, AddRef, Release    the layer's own three functions; a body file or an
                                       accept line for one of them is an error
    a body file exists                 <bodies>/<I>/<M>.c, or else <bodies>/<B>/<M>.c for the
                                       nearest base B of I that has the method: the thunk
                                       calls its typed function.  The file's COM_METHOD line
                                       must repeat the description's prototype exactly
    the accept list names it           `<I>::<M>` or `<B>::<M>`: the thunk checks `this` and
                                       returns S_OK (HRESULT) or nothing (void); any other
                                       return type is an error
    otherwise                          the stop (rt_com_stop)
A body file and an accept line for the same method are an error.  A file in a subdirectory of
the bodies directory that is the body of no described method is an error, and so is an accept
line that marks none: nothing is ever silently unused.

A GUARD (--guard FILE; runtime/com/guard.def says what it is for) is a pair of functions a
thunk calls around its body, for every method of an interface after IUnknown's three or for
one method: `enter` after the call was counted and before the body, with `this` and the
method's row, and `leave` with what `enter` returned, before the thunk returns.  A method that
stops has no guard.  A line that marks no described method is an error.

A body registers itself by existing: nothing else lists bodies.  Every problem names its file
and nothing is written in that case.

Single process, standard library only.  Run by runtime/rt.mk; never by hand into the source tree.
"""

