def typed_decl(p):
    return "%s%s%s" % (p.ctype, "" if p.ctype.endswith("*") else " ", p.name)


def thunk(m, prefix):
    it = m.iface
    o = ["/* %s::%s   slot %d   %s */" % (it.name, m.name, m.slot, m.body_rel or it.rel)]
    rsep = "" if m.ret.ctype.endswith("*") else " "
    if m.body == "FILE":
        this = "%s *This" % m.body_iface
        o.append("%s%simpl_%s_%s(%s);" % (m.ret.ctype, rsep, m.body_iface, m.name,
                                          ", ".join(["Ctx *ctx", this] + [typed_decl(p) for p in m.params[1:]])))
    o.append("void %s_%s(Ctx *ctx)" % (prefix, m.sym))
    o.append("{")
    o.append("    RT_COM_ENTER(ctx, &rt_iface_%s_methods[%d], &rt_iface_%s_counts[%d]);" % (it.name, m.slot, it.name, m.slot))
    leave = []
    if m.guard:
        o.insert(1, "void *%s(Ctx *ctx, void *This, const RtComMethod *m);\nvoid %s(void *guard);" % m.guard)
        o.append("    void *guard_ = %s(ctx, (void *)(uintptr_t)ARG_U64(ctx, 0), &rt_iface_%s_methods[%d]);" % (m.guard[0], it.name, m.slot))
        leave = ["    %s(guard_);" % m.guard[1]]
    if m.body == "STOP":
        o.append("    rt_com_stop(ctx);")
        o.append("}")
        return "\n".join(o) + "\n"
    if m.body == "ACCEPT":
        o.append("    rt_com_accept(ctx, (void *)(uintptr_t)ARG_U64(ctx, 0));")
        if m.ret.cls != "void":
            o.append("    RET_U32(ctx, S_OK);")
        o += leave
        o.append("    RT_SHIM_LEAVE(ctx);")
        o.append("}")
        return "\n".join(o) + "\n"
    for i, p in enumerate(m.params):
        o.append("    " + gen_shims.fetch_arg(p, "a%d" % i, i))
    names = ["a%d" % i for i in range(len(m.params))]
    if m.body == "UNKNOWN":
        call = "rt_com_%s(%s)" % (m.name, ", ".join(["ctx"] + names))
    else:
        names[0] = "(%s *)a0" % m.body_iface
        call = "impl_%s_%s(%s)" % (m.body_iface, m.name, ", ".join(["ctx"] + names))
    st = gen_shims.store_ret(m.ret)
    if st is None:
        o.append("    %s;" % call)
    else:
        o.append("    %s%sr_ = %s;" % (m.ret.ctype, rsep, call))
        o.append("    " + st)
    o += leave
    o.append("    RT_SHIM_LEAVE(ctx);")
    o.append("}")
    return "\n".join(o) + "\n"


def call_wrapper(m):
    it = m.iface
    rsep = "" if m.ret.ctype.endswith("*") else " "
    o = ["static inline __attribute__((unused)) %s%srt_comcall_%s(%s)" % (
        m.ret.ctype, rsep, m.sym, ", ".join(typed_decl(p) for p in m.params)), "{"]
    o.append("    const RtTestArg a_[%d] = {" % len(m.params))
    for p in m.params:
        o.append("        %s," % gen_shims.test_arg(p, p.name))
    o.append("    };")
    call = "rt_test_com_call(&rt_iface_%s, %d, %d, a_)" % (it.name, m.slot, len(m.params))
    c = m.ret.cls
    if c == "void":
        o.append("    (void)%s;" % call)
    else:
        o.append("    RtTestRet r_ = %s;" % call)
        if c in INT_CLASSES or c == "guestfn":
            o.append("    return (%s)r_.rax;" % m.ret.ctype)
        elif c in POINTER_CLASSES:
            o.append("    return (%s)(uintptr_t)r_.rax;" % m.ret.ctype)
        elif c == "f32":
            o.append("    return r_.xmm0.f[0];")
        elif c == "f64":
            o.append("    return r_.xmm0.pd[0];")
        elif c == "struct8":
            o.append("    %s v_; memcpy(&v_, &r_.rax, sizeof v_); return v_;" % m.ret.ctype)
    o.append("}")
    return "\n".join(o) + "\n"


def types_header(paths, known_includes, guard):
    """The C declarations of every row with a `#=` definition in the types files."""
    o = [HEADER, "#ifndef RT_GEN_%s\n#define RT_GEN_%s\n\n" % (guard, guard), '#include "rt/shim.h"\n']
    o += ['#include "%s"\n' % h for h in known_includes]
    o.append("\n")
    for path in paths:
        for n, raw in enumerate(open(path), 1):
            if "#=" not in raw or raw.lstrip().startswith("#"):
                continue
            name = raw.split("#", 1)[0].split()[0]
            c = raw.split("#=", 1)[1].strip()
            if c == "enum":
                o.append("typedef uint32_t %s;\n" % name)
            elif c in ("struct", "interface"):
                o.append("typedef struct %s %s;\n" % (name, name))
            elif re.fullmatch(r"[A-Za-z_]\w*", c):
                o.append("typedef %s %s;\n" % (c, name))
            else:
                raise ShimError("%s:%d: after `#=`: enum, struct, interface or a type name" % (path, n))
    o.append("\n#endif\n")
    return "".join(o)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--desc", required=True, help="directory of <Interface>.idef files")
    ap.add_argument("--types", action="append", required=True, help="types file (repeatable); rows with `#=` are declared in <prefix>_types.h")
    ap.add_argument("--accept", help="the accept list")
    ap.add_argument("--bodies", action="append", default=[],
                    help="directory of <Interface>/<Method>.c body files (repeatable; one body in one directory only)")
    ap.add_argument("--guard", help="the guard list: functions a thunk calls around its body")
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument("--prefix", default="com", help="prefix of the output file names and of the thunks")
    ap.add_argument("--table", default="rt_com_table", help="C name of the RtComTable")
    ap.add_argument("--root", default=".", help="repository root, for the paths recorded in the tables")
    args = ap.parse_args()
    P = args.prefix

    try:
        types, includes = shimdef.load_types(args.types)
        own = "%s_types.h" % P
        ifaces = [load_desc(os.path.join(args.desc, f), types, args.root)
                  for f in sorted(os.listdir(args.desc)) if f.endswith(".idef")]
        if not ifaces:
            raise ShimError("%s: no .idef file" % args.desc)
        check_roots(ifaces)
        accept = load_accept(args.accept, args.root)
        decide(ifaces, accept, args.bodies, types, args.root)
        apply_guard(ifaces, load_guard(args.guard, args.root))
        types_h = types_header(args.types, [h for h in includes if not h.endswith("_types.h")], "%s_TYPES_H" % P.upper())
    except ShimError as e:
        sys.exit("gen_com: %s" % e)
    except (OSError, UnicodeDecodeError) as e:
        sys.exit("gen_com: %s" % e)
    other_types = "".join('#include "%s"\n' % h for h in includes if h.endswith("_types.h") and h != own)

    # ---- ids ----
    o = [HEADER, "#ifndef RT_GEN_%s_IDS_H\n#define RT_GEN_%s_IDS_H\n\n" % (P.upper(), P.upper()),
         '#include "rt/com.h"\n', other_types, '#include "%s"\n\n' % own, "extern RtComTable %s;\n\n" % args.table]
    for it in ifaces:
        o.append("extern RtComIface rt_iface_%s;\nextern const RtComMethod rt_iface_%s_methods[];\n"
                 "extern RtComCount rt_iface_%s_counts[];\n" % (it.name, it.name, it.name))
        for m in it.methods:
            o.append("#define RT_COM_SLOT_%s %d\n" % (m.sym, m.slot))
        o.append("\n")
    o.append("#endif\n")
    ids = "".join(o)

    # ---- thunks ----
    o = [HEADER, '#include "rt/win/error.h"\n', '#include "%s_ids.h"\n\n' % P]
    for it in ifaces:
        for m in it.methods:
            o.append(thunk(m, P))
            o.append("\n")
    thunks = "".join(o)

    # ---- tables ----
    o = [HEADER, '#include "%s_ids.h"\n\n' % P]
    for it in ifaces:
        for m in it.methods:
            o.append("void %s_%s(Ctx *ctx);\n" % (P, m.sym))
    o.append("\n")
    for it in ifaces:
        lib = shimdef.lib_id(it.owner)
        for m in it.methods:
            o.append("static const uint8_t args_%s[] = { %s };\n" % (m.sym, ", ".join(p.enum for p in m.params)))
            o.append("static const char *const types_%s[] = { %s };\n" % (m.sym, ", ".join(cstr(p.ctype) for p in m.params)))
            o.append("static const char *const names_%s[] = { %s };\n" % (m.sym, ", ".join(cstr(p.name) for p in m.params)))
        o.append("const RtComMethod rt_iface_%s_methods[] = {\n" % it.name)
        for m in it.methods:
            o.append("    { { %s, %s, 0, %s_%s, %s, %d, %s, 0, args_%s, %s },\n      &rt_iface_%s, %s, %s, %s, types_%s, names_%s,\n"
                     "      %s, %d, RT_COM_BODY_%s },\n" % (
                         cstr(lib), cstr("%s::%s" % (it.name, m.name)), P, m.sym, m.ret.enum, len(m.params),
                         STATUS_ENUM[m.status], m.sym, cstr(m.body_rel or it.rel),
                         it.name, cstr(m.name), cstr(m.declared_by), cstr(m.ret.ctype), m.sym, m.sym,
                         cstr(m.where), m.slot, m.body))
        o.append("};\n")
        o.append("static const RtComAncestor chain_%s[] = {\n" % it.name)
        for b, iid, nslots in it.chain:
            o.append("    { %s, %s, %d },\n" % (cstr(b), guid_init(iid, it.rel), nslots))
        o.append("};\n")
        o.append("RtComCount rt_iface_%s_counts[%d];\n" % (it.name, len(it.methods)))
        o.append("RtComIface rt_iface_%s = { %s, %s, %s, %s, chain_%s, %d,\n    rt_iface_%s_methods, rt_iface_%s_counts, %d, 0 };\n\n" % (
            it.name, cstr(it.name), guid_init(it.iid, it.rel), cstr(it.owner), cstr(it.header), it.name, len(it.chain),
            it.name, it.name, len(it.methods)))
    o.append("static RtComIface *const ifaces_[] = {\n")
    for it in ifaces:
        o.append("    &rt_iface_%s,\n" % it.name)
    o.append("};\n")
    o.append("RtComTable %s = { ifaces_, %d, %s, NULL };\n" % (
        args.table, len(ifaces), cstr(os.path.relpath(args.desc, args.root).replace(os.sep, "/"))))
    tables = "".join(o)

    # ---- test call wrappers ----
    o = [HEADER,
         "/* Typed wrappers behind COM_CALL(Interface, Method, this, ...) of rt/test.h.  Test files only. */\n",
         "#ifndef RT_GEN_%s_CALLS_H\n#define RT_GEN_%s_CALLS_H\n\n" % (P.upper(), P.upper()),
         '#include "rt/test.h"\n', '#include "%s_ids.h"\n\n' % P]
    for it in ifaces:
        for m in it.methods:
            o.append(call_wrapper(m))
            o.append("\n")
    o.append("#endif\n")
    calls = "".join(o)

    os.makedirs(args.out, exist_ok=True)
    for name, text in (("types.h", types_h), ("ids.h", ids), ("thunks.c", thunks), ("table.c", tables), ("calls.h", calls)):
        gen_shims.write_if_changed(os.path.join(args.out, "%s_%s" % (P, name)), text)


if __name__ == "__main__":
    main()
