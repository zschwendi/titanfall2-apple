#!/usr/bin/env python3
"""Generate the shim thunks and tables (docs/RUNTIME.md sections 3.1, 3.2, 10.3).

Reads every <shims dir>/<lib>/<Name>.c, parses the one-line SHIM / SHIM_ORD / SHIM_RAW
declaration and the four RT-* header tags, and writes into the output directory:

    <prefix>_thunks.c       one thunk per shim: fetches the arguments from the guest registers
                            and stack as section 3.1 says and calls the typed implementation
    <prefix>_table.c        the shim table (library, name, ordinal, thunk, argument classes,
                            status) and the module table from modules.def
    <prefix>_ids.h          RT_ID_<lib>_<Name>: the address of each shim's table row
    <prefix>_calls.h        typed wrappers behind CALL() in rt/test.h: call a shim through the
                            guest ABI from a test
    <prefix>_types_check.c  _Static_assert that every type in types.def has the size its
                            class says

A shim registers itself by existing: nothing else lists shims.  An unknown type, a forbidden
type (long, wchar_t, size_t), a missing header tag or a declaration that is not one line is an
error that names the file; nothing is written in that case.

    .venv/bin/python runtime/tools/gen_shims.py --shims runtime/shims \
        --types runtime/tools/types.def --modules runtime/modules.def --out build/gen

Single process, standard library only.  Run by runtime/rt.mk; never run it by hand into the
source tree.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shimdef                                                     # noqa: E402
from shimdef import CLASSES, INT_CLASSES, POINTER_CLASSES, ShimError  # noqa: E402

HEADER = "/* Generated by runtime/tools/gen_shims.py.  Do not edit; never commit. */\n"
STATUS_ENUM = {"full": "RT_ST_FULL", "partial": "RT_ST_PARTIAL", "absent": "RT_ST_ABSENT",
               "advisory": "RT_ST_ADVISORY", "trap": "RT_ST_TRAP"}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def decl_params(shim, with_ctx):
    parts = ["Ctx *ctx"] if with_ctx else []
    for p in shim.params:
        sep = "" if p.ctype.endswith("*") else " "
        parts.append("%s%s%s" % (p.ctype, sep, p.name))
    return ", ".join(parts) if parts else "void"


def fetch_arg(p, local, n):
    """C statement that loads declared argument `p` from ABI position n into `local`."""
    sep = "" if p.ctype.endswith("*") else " "
    if p.cls in INT_CLASSES or p.cls == "guestfn":
        return "%s%s%s = (%s)ARG_U64(ctx, %d);" % (p.ctype, sep, local, p.ctype, n)
    if p.cls in POINTER_CLASSES:
        return "%s%s%s = (%s)(uintptr_t)ARG_U64(ctx, %d);" % (p.ctype, sep, local, p.ctype, n)
    if p.cls == "f32":
        return "%s %s = ARG_F32(ctx, %d);" % (p.ctype, local, n)
    if p.cls == "f64":
        return "%s %s = ARG_F64(ctx, %d);" % (p.ctype, local, n)
    if p.cls == "struct8":
        return "%s %s; { uint64_t v_ = ARG_U64(ctx, %d); memcpy(&%s, &v_, sizeof %s); }" % (
            p.ctype, local, n, local, local)
    if p.cls == "struct":
        return "%s %s; memcpy(&%s, (const void *)(uintptr_t)ARG_U64(ctx, %d), sizeof %s);" % (
            p.ctype, local, local, n, local)
    raise AssertionError(p.cls)


def store_ret(ret):
    c = ret.cls
    if c == "void":
        return None
    if c in ("i8", "i16"):
        return "RET_U32(ctx, (uint32_t)(int32_t)r_);"
    if c in ("u8", "u16", "i32", "u32"):
        return "RET_U32(ctx, r_);"
    if c in ("i64", "u64", "guestfn"):
        return "RET_U64(ctx, r_);"
    if c in POINTER_CLASSES:
        return "RET_U64(ctx, (uintptr_t)r_);"
    if c == "f32":
        return "RET_F32(ctx, r_);"
    if c == "f64":
        return "RET_F64(ctx, r_);"
    if c == "struct8":
        return "{ uint64_t v_ = 0; memcpy(&v_, &r_, sizeof r_); RET_U64(ctx, v_); }"
    if c == "struct":
        return "memcpy((void *)(uintptr_t)dst_, &r_, sizeof r_); RET_U64(ctx, dst_);"
    raise AssertionError(c)


def thunk(shim, table):
    sym = "%s_%s" % (shim.lib, shim.name)
    o = ["/* %s!%s   %s:%d */" % (shim.lib, shim.name, shim.rel, shim.line)]
    if shim.raw:
        o.append("void raw_%s(Ctx *ctx);" % sym)
        o.append("void shim_%s(Ctx *ctx)" % sym)
        o.append("{")
        o.append("    RT_SHIM_ENTER(ctx, RT_ID_%s);" % sym)
        o.append("    raw_%s(ctx);" % sym)
        o.append("    RT_SHIM_LEAVE(ctx);")
        o.append("}")
        return "\n".join(o) + "\n"
    rsep = "" if shim.ret.ctype.endswith("*") else " "
    o.append("%s%simpl_%s(%s);" % (shim.ret.ctype, rsep, sym, decl_params(shim, True)))
    o.append("void shim_%s(Ctx *ctx)" % sym)
    o.append("{")
    o.append("    RT_SHIM_ENTER(ctx, RT_ID_%s);" % sym)
    shift = 0
    if shim.sret:
        o.append("    uint64_t dst_ = ARG_U64(ctx, 0);      /* hidden argument 0: where the struct goes */")
        shift = 1
    for i, p in enumerate(shim.params):
        o.append("    " + fetch_arg(p, "a%d" % i, i + shift))
    call = "impl_%s(%s)" % (sym, ", ".join(["ctx"] + ["a%d" % i for i in range(len(shim.params))]))
    st = store_ret(shim.ret)
    if st is None:
        o.append("    %s;" % call)
    else:
        o.append("    %s%sr_ = %s;" % (shim.ret.ctype, rsep, call))
        o.append("    " + st)
    o.append("    RT_SHIM_LEAVE(ctx);")
    o.append("}")
    return "\n".join(o) + "\n"


def test_arg(p, expr):
    """RtTestArg initialiser for declared argument `p` whose value is the C expression `expr`."""
    if p.cls in INT_CLASSES or p.cls == "guestfn":
        return "{ %s, %d, { .u = (uint64_t)(%s) } }" % (p.enum, p.size, expr)
    if p.cls in POINTER_CLASSES:
        return "{ %s, 8, { .u = (uint64_t)(uintptr_t)(%s) } }" % (p.enum, expr)
    if p.cls == "f32":
        return "{ %s, 4, { .f = (%s) } }" % (p.enum, expr)
    if p.cls == "f64":
        return "{ %s, 8, { .d = (%s) } }" % (p.enum, expr)
    if p.cls == "struct8":
        return "{ %s, %d, { .u = rt_test_pack(&%s, sizeof %s) } }" % (p.enum, p.size, expr, expr)
    if p.cls == "struct":
        return "{ %s, 8, { .u = (uint64_t)(uintptr_t)&%s } }" % (p.enum, expr)
    raise AssertionError(p.cls)


def call_wrapper(shim):
    sym = "%s_%s" % (shim.lib, shim.name)
    o = []
    if shim.raw:
        o.append("/* %s!%s is SHIM_RAW: pass the argument slots yourself; returns rax. */" % (shim.lib, shim.name))
        o.append("static inline __attribute__((unused)) uint64_t rt_call_%s(unsigned n, const uint64_t *slots)" % sym)
        o.append("{")
        o.append("    return rt_test_call_raw(RT_ID_%s, n, slots).rax;" % sym)
        o.append("}")
        return "\n".join(o) + "\n"
    rsep = "" if shim.ret.ctype.endswith("*") else " "
    o.append("static inline __attribute__((unused)) %s%srt_call_%s(%s)" % (
        shim.ret.ctype, rsep, sym, decl_params(shim, False)))
    o.append("{")
    args = []
    if shim.sret:
        o.append("    %s ret_;" % shim.ret.ctype)
        o.append("    memset(&ret_, 0xA5, sizeof ret_);")
        args.append("{ RT_AC_PTR, 8, { .u = (uint64_t)(uintptr_t)&ret_ } }")
    for p in shim.params:
        args.append(test_arg(p, p.name))
    n = len(args)
    if n:
        o.append("    const RtTestArg a_[%d] = {" % n)
        for a in args:
            o.append("        %s," % a)
        o.append("    };")
    call = "rt_test_call(RT_ID_%s, %d, %s, %d)" % (sym, n, "a_" if n else "NULL", 1 if shim.sret else 0)
    c = shim.ret.cls
    if c == "void":
        o.append("    (void)%s;" % call)
    else:
        o.append("    RtTestRet r_ = %s;" % call)
        if c in INT_CLASSES or c == "guestfn":
            o.append("    return (%s)r_.rax;" % shim.ret.ctype)
        elif c in POINTER_CLASSES:
            o.append("    return (%s)(uintptr_t)r_.rax;" % shim.ret.ctype)
        elif c == "f32":
            o.append("    return r_.xmm0.f[0];")
        elif c == "f64":
            o.append("    return r_.xmm0.pd[0];")
        elif c == "struct8":
            o.append("    %s v_; memcpy(&v_, &r_.rax, sizeof v_); return v_;" % shim.ret.ctype)
        elif c == "struct":
            o.append("    rt_test_check_sret(RT_ID_%s, r_, &ret_);" % sym)
            o.append("    return ret_;")
    o.append("}")
    return "\n".join(o) + "\n"


def write_if_changed(path, text):
    try:
        if open(path).read() == text:
            return
    except OSError:
        pass
    with open(path, "w") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--shims", action="append", default=[], help="directory holding <lib>/<Name>.c (repeatable)")
    ap.add_argument("--types", action="append", required=True, help="types.def (repeatable)")
    ap.add_argument("--modules", required=True, help="modules.def: the modules the shims may belong to")
    ap.add_argument("--out", required=True, help="output directory")
    ap.add_argument("--prefix", default="shim", help="prefix of the output file names")
    ap.add_argument("--table", default="rt_shim_table", help="C name of the shim table; the count is <name minus _table>_count")
    ap.add_argument("--module-table", default="rt_module_defs", help="C name of the module table")
    ap.add_argument("--allow-unchecked", action="store_true",
                    help="accept `identity=unchecked` on lifted rows (test manifests only)")
    ap.add_argument("--root", default=".", help="repository root, for the paths recorded in the table")
    args = ap.parse_args()

    try:
        types, includes = shimdef.load_types(args.types)
        modules = shimdef.load_modules(args.modules, args.allow_unchecked)
        shims = [shimdef.parse_shim(p, types, args.root) for p in shimdef.find_shims(args.shims)]
        by_lib = {m["lib"]: m for m in modules}
        seen = {}
        for s in shims:
            m = by_lib.get(s.lib)
            if m is None:
                raise ShimError("%s:%d: library '%s' is not a module in %s; a new library is added by "
                                "the planner" % (s.rel, s.line, s.lib, args.modules))
            if m["kind"] == "lifted":
                raise ShimError("%s:%d: '%s' is a lifted module in %s; lifted modules have no shims" % (
                    s.rel, s.line, m["file"], args.modules))
            key = (s.lib, s.name)
            if key in seen:
                raise ShimError("%s:%d: %s!%s is already implemented in %s" % (
                    s.rel, s.line, s.lib, s.name, seen[key].rel))
            seen[key] = s
            if s.ordinal:
                okey = (s.lib, s.ordinal)
                if okey in seen:
                    raise ShimError("%s:%d: ordinal %d of %s is already implemented in %s" % (
                        s.rel, s.line, s.ordinal, s.lib, seen[okey].rel))
                seen[okey] = s
    except ShimError as e:
        sys.exit("gen_shims: %s" % e)
    except OSError as e:
        sys.exit("gen_shims: %s" % e)

    shims.sort(key=lambda s: (s.lib, s.name))
    table = args.table
    count = (table[:-len("_table")] if table.endswith("_table") else table) + "_count"
    mcount = (args.module_table[:-1] if args.module_table.endswith("s") else args.module_table) + "_count"
    extra_inc = "".join('#include "%s"\n' % h for h in includes)

    # ---- ids ----
    o = [HEADER, "#ifndef RT_GEN_%s_IDS_H\n#define RT_GEN_%s_IDS_H\n\n" % (args.prefix.upper(), args.prefix.upper()),
         '#include "rt/module.h"\n\n',
         "extern const RtShimEntry %s[];\nextern const unsigned %s;\n" % (table, count),
         "extern const RtModuleDef %s[];\nextern const unsigned %s;\n\n" % (args.module_table, mcount)]
    for i, s in enumerate(shims):
        o.append("#define RT_ID_%s_%s (&%s[%d])\n" % (s.lib, s.name, table, i))
    o.append("\n#endif\n")
    ids = "".join(o)

    # ---- thunks ----
    o = [HEADER, '#include "rt/shim.h"\n', extra_inc, '#include "%s_ids.h"\n\n' % args.prefix]
    for s in shims:
        o.append(thunk(s, table))
        o.append("\n")
    thunks = "".join(o)

    # ---- tables ----
    o = [HEADER, '#include "rt/shim.h"\n', '#include "%s_ids.h"\n\n' % args.prefix]
    for s in shims:
        o.append("void shim_%s_%s(Ctx *ctx);\n" % (s.lib, s.name))
    o.append("\n")
    for i, s in enumerate(shims):
        if s.params:
            o.append("static const uint8_t args_%d[] = { %s };\n" % (i, ", ".join(p.enum for p in s.params)))
    o.append("\n/* Sorted by library, then name.  The last row is a terminator that is not counted. */\n")
    o.append("const RtShimEntry %s[] = {\n" % table)
    for i, s in enumerate(shims):
        o.append("    { %s, %s, %d, shim_%s_%s, %s, %d, %s, %d, %s, %s },\n" % (
            cstr(s.lib), cstr(s.name), s.ordinal, s.lib, s.name,
            "RT_AC_VOID" if s.raw else s.ret.enum, len(s.params), STATUS_ENUM[s.status],
            1 if s.raw else 0, ("args_%d" % i) if s.params else "NULL", cstr(s.rel)))
    o.append("    { NULL, NULL, 0, NULL, 0, 0, 0, 0, NULL, NULL }\n};\n")
    o.append("const unsigned %s = %d;\n\n" % (count, len(shims)))
    o.append("/* %s, in order.  A lifted row points at the lifted C the program links (rt/module.h). */\n" % args.modules)
    for m in modules:
        if m["kind"] == "lifted":
            o.append("extern uint64_t g_base_%s;\nextern const LiftedEntry %s_table[];\nextern const size_t %s_table_count;\n"
                     "extern const LiftedSkip %s_skips[];\nextern const size_t %s_skips_count;\n"
                     "static const RtLiftedCode code_%s = { %s, &g_base_%s, %s_table, &%s_table_count, %s_skips, &%s_skips_count };\n" % (
                         (m["module"],) * 6 + (cstr(m["module"]),) + (m["module"],) * 5))
    o.append("const RtModuleDef %s[] = {\n" % args.module_table)
    for m in modules:
        o.append("    { %s, %s, 0x%x, %d, 0x%x, %s, %s, %s, %s },\n" % (
            shimdef.MODULE_KINDS[m["kind"]], cstr(m["file"]), m["size_of_image"], m["file_size"],
            m["timestamp"], cstr(m["sha256"]) if m["sha256"] else "NULL",
            ("&code_%s" % m["module"]) if m["kind"] == "lifted" else "NULL",
            cstr(m["dir"]) if m["dir"] is not None else "NULL",
            " | ".join((["RT_MODDEF_UNCHECKED"] if m["unchecked"] else []) + (["RT_MODDEF_LATE"] if m["late"] else [])) or "0"))
    o.append("    { 0, NULL, 0, 0, 0, NULL, NULL, NULL, 0 }\n};\n")
    o.append("const unsigned %s = %d;\n" % (mcount, len(modules)))
    tables = "".join(o)

    # ---- test call wrappers ----
    o = [HEADER,
         "/* Typed wrappers behind CALL(lib, Name, ...) of rt/test.h.  Included by test files only. */\n",
         "#ifndef RT_GEN_%s_CALLS_H\n#define RT_GEN_%s_CALLS_H\n\n" % (args.prefix.upper(), args.prefix.upper()),
         '#include "rt/test.h"\n', extra_inc, '#include "%s_ids.h"\n\n' % args.prefix]
    for s in shims:
        o.append(call_wrapper(s))
        o.append("\n")
    o.append("#endif\n")
    calls = "".join(o)

    # ---- types check ----
    o = [HEADER, "/* Every name in %s must have the size its class says. */\n" % ", ".join(args.types),
         '#include "rt/shim.h"\n', extra_inc, "\n"]
    for name in sorted(types):
        t = types[name]
        if t.cls == "void":
            continue
        o.append('_Static_assert(sizeof(%s) == %d, "%s: %s is class %s (%d bytes)");\n' % (
            name, t.size, t.where, name, t.cls, t.size))
        if t.cls in ("f32",):
            o.append('_Static_assert(_Generic((%s)0, float: 1, default: 0), "%s: %s is class f32 but is not float");\n' % (
                name, t.where, name))
        if t.cls in ("f64",):
            o.append('_Static_assert(_Generic((%s)0, double: 1, default: 0), "%s: %s is class f64 but is not double");\n' % (
                name, t.where, name))
    check = "".join(o)

    os.makedirs(args.out, exist_ok=True)
    for name, text in (("ids.h", ids), ("thunks.c", thunks), ("table.c", tables),
                       ("calls.h", calls), ("types_check.c", check)):
        write_if_changed(os.path.join(args.out, "%s_%s" % (args.prefix, name)), text)


if __name__ == "__main__":
    main()
