/* Called by rt_init after the machine description exists.  The tables above are en-US and
 * code pages 1252 / 437 only; if the machine description says otherwise the two disagree,
 * which section 8 of RUNTIME.md forbids, so stop. */
static bool initialized;

bool rt_locale_initialized(void) { return initialized; }

void rt_locale_init(void) {
    const RtMachine *m = rt_machine();
    if (m->lcid != LANG_ENGLISH_US_LCID || m->ansi_cp != RT_CP_ANSI || m->oem_cp != RT_CP_OEM)
        rt_fatal("the locale tables are en-US / 1252 / 437, but the machine description says locale %#x, ANSI %u, OEM %u",
                 m->lcid, m->ansi_cp, m->oem_cp);
    /* The run tables are binary-searched: a mistake in an edit would silently break lookups. */
    for (unsigned i = 1; i < sizeof upper_runs / sizeof upper_runs[0]; i++)
        if (upper_runs[i].lo <= upper_runs[i - 1].hi) rt_fatal("locale: upper_runs not sorted at %u", i);
    for (unsigned i = 1; i < sizeof lower_runs / sizeof lower_runs[0]; i++)
        if (lower_runs[i].lo <= lower_runs[i - 1].hi) rt_fatal("locale: lower_runs not sorted at %u", i);
    for (unsigned i = 1; i < sizeof ctype_runs / sizeof ctype_runs[0]; i++)
        if (ctype_runs[i].lo < ctype_runs[i - 1].lo + ctype_runs[i - 1].count) rt_fatal("locale: ctype_runs not sorted at %u", i);
    for (unsigned i = 1; i < sizeof case_uncovered / sizeof case_uncovered[0]; i++)
        if (case_uncovered[i][0] <= case_uncovered[i - 1][1]) rt_fatal("locale: case_uncovered not sorted at %u", i);
    initialized = true;
}
