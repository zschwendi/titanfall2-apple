/* The calling guest thread's Ctx, for the report of rt_unimplemented (NULL on a host thread
 * that is not a guest thread, which the report copes with). */
static Ctx *loc_ctx(void) {
    RtThread *t = rt_thread_self();
    return t ? &t->ctx : NULL;
}

/* A case this core does not handle: one FATAL block naming the Windows function, the case
 * and the value.  Never returns. */
#define UNIMPL(...)  rt_unimplemented(loc_ctx(), __FILE__, __LINE__, __VA_ARGS__)

/* Fail with a last error; the value is the Windows failure value 0 / FALSE. */
static int fail(DWORD err) {
    rt_thread_set_last_error(err);
    return 0;
}

static bool ranges_overlap(const void *a, uint64_t alen, const void *b, uint64_t blen) {
    uintptr_t a0 = (uintptr_t)a, a1 = a0 + (uintptr_t)alen;
    uintptr_t b0 = (uintptr_t)b, b1 = b0 + (uintptr_t)blen;
    return a0 < b1 && b0 < a1;
}

/* Length of a NUL-terminated string including the NUL, as an int.  A string whose length
 * does not fit is a bug in the guest that Windows would turn into an overflow; refuse. */
static int len_with_nul_a(const char *s, const char *api) {
    int64_t n = 0;
    while (s[n]) n++;
    if (n + 1 > INT_MAX) UNIMPL("%s: a NUL-terminated string of 2 GiB or more", api);
    return (int)(n + 1);
}
static int len_with_nul_w(const WCHAR *s, const char *api) {
    int64_t n = 0;
    while (s[n]) n++;
    if (n + 1 > INT_MAX) UNIMPL("%s: a NUL-terminated string of 2 GiB or more", api);
    return (int)(n + 1);
}
static int len_w(const WCHAR *s, const char *api) { return len_with_nul_w(s, api) - 1; }

