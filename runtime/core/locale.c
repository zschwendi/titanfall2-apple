/* The calendar arithmetic is the proleptic Gregorian calendar, as GetDateFormat uses for
 * en-US.  Days are counted from 1601-01-01 (FILETIME zero). */
static bool is_leap(unsigned y) { return (y % 4 == 0 && y % 100 != 0) || y % 400 == 0; }
static unsigned days_in_month(unsigned y, unsigned m) {
    static const uint8_t d[12] = { 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31 };
    return m == 2 && is_leap(y) ? 29 : d[m - 1];
}
/* 0 = Sunday. */
static unsigned weekday(unsigned y, unsigned m, unsigned d) {
    static const uint8_t t[12] = { 0, 3, 2, 5, 0, 3, 5, 1, 4, 6, 2, 4 };
    if (m < 3) y--;
    return (y + y / 4 - y / 100 + y / 400 + t[m - 1] + d) % 7;
}

void rt_systemtime_from_filetime(uint64_t ft, RtSystemTime *out) {
    uint64_t ms_total = ft / 10000;
    uint64_t days = ms_total / 86400000;
    uint32_t ms_day = (uint32_t)(ms_total % 86400000);
    /* days since 1601-01-01 -> civil date (Howard Hinnant's algorithm, epoch moved to 0000-03-01). */
    int64_t z = (int64_t)days + 584694;              /* 0000-03-01 to 1601-01-01 is 584694 days (719468 to 1970-01-01, less 134774) */
    int64_t era = z / 146097;
    int64_t doe = z - era * 146097;
    int64_t yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    int64_t y = yoe + era * 400;
    int64_t doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    int64_t mp = (5 * doy + 2) / 153;
    int64_t d = doy - (153 * mp + 2) / 5 + 1;
    int64_t m = mp < 10 ? mp + 3 : mp - 9;
    if (m <= 2) y++;
    out->wYear = (WORD)y;
    out->wMonth = (WORD)m;
    out->wDay = (WORD)d;
    out->wDayOfWeek = (WORD)((days + 1) % 7);        /* 1601-01-01 was a Monday */
    out->wHour = (WORD)(ms_day / 3600000);
    out->wMinute = (WORD)(ms_day / 60000 % 60);
    out->wSecond = (WORD)(ms_day / 1000 % 60);
    out->wMilliseconds = (WORD)(ms_day % 1000);
}

bool rt_filetime_from_systemtime(const RtSystemTime *st, uint64_t *filetime) {
    if (!st || !filetime)
        rt_fatal("rt_filetime_from_systemtime: a NULL pointer (time %p, result %p)", (const void *)st, (void *)filetime);
    if (st->wYear < 1601 || st->wYear > 30827 || st->wMonth < 1 || st->wMonth > 12 ||
        st->wDay < 1 || st->wDay > days_in_month(st->wYear, st->wMonth) ||
        st->wHour > 23 || st->wMinute > 59 || st->wSecond > 59 || st->wMilliseconds > 999)
        return fail(ERROR_INVALID_PARAMETER) != 0;
    /* civil date -> days since 1601-01-01: the inverse of the algorithm above, with the year
     * counted from 1 March so that the leap day is the last day of its year. */
    const int64_t y = (int64_t)st->wYear - (st->wMonth <= 2);
    const int64_t era = y / 400;
    const int64_t yoe = y - era * 400;
    const int64_t doy = (153 * ((int64_t)st->wMonth + (st->wMonth > 2 ? -3 : 9)) + 2) / 5 + st->wDay - 1;
    const int64_t doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    const uint64_t days = (uint64_t)(era * 146097 + doe - 584694);
    const uint64_t ms = ((days * 24 + st->wHour) * 60 + st->wMinute) * 60000 + (uint64_t)st->wSecond * 1000 + st->wMilliseconds;
    *filetime = ms * 10000;
    return true;
}

/* The current local time, for a NULL date or time: the UTC clock of rt/time.h less the
 * time zone bias (which has no daylight-saving rule). */
static void now_local(RtSystemTime *st) {
    int64_t local = (int64_t)rt_time_utc_100ns() - (int64_t)rt_time_zone_bias_minutes() * INT64_C(600000000);
    rt_systemtime_from_filetime((uint64_t)local, st);
}

/* Output that counts what it is given and writes what fits. */
typedef struct { WCHAR *buf; int cap; int64_t n; } Out;
static void out_put(Out *o, WCHAR c) {
    if (o->cap > 0 && o->n < o->cap) o->buf[o->n] = c;
    o->n++;
}
static void out_str(Out *o, const char *s) { while (*s) out_put(o, (uint8_t)*s++); }
static void out_num(Out *o, unsigned v, int width) {
    char tmp[12];
    int n = 0;
    do { tmp[n++] = (char)('0' + v % 10); v /= 10; } while (v);
    for (int i = n; i < width; i++) out_put(o, '0');
    while (n) out_put(o, (uint8_t)tmp[--n]);
}
static int out_finish(Out *o) {
    int64_t total = o->n + 1;                        /* the NUL */
    if (o->cap == 0) return total > INT_MAX ? fail(ERROR_INSUFFICIENT_BUFFER) : (int)total;
    if (total > o->cap) return fail(ERROR_INSUFFICIENT_BUFFER);
    o->buf[o->n] = 0;
    return (int)total;
}

static unsigned run_length(const WCHAR *p, WCHAR c) { unsigned n = 0; while (p[n] == c) n++; return n; }

/* The format picture engine shared by the two functions.  Quoting: text in single quotes
 * is copied, '' inside quotes is one quote, an unterminated quote runs to the end of the
 * picture.  A letter that is not a picture letter of this function is copied as itself
 * (that is how I read the documentation: "the function ... just forms the best possible
 * string"; not verified for letters). */
static void emit_picture(Out *o, const WCHAR *pic, bool is_date, const RtSystemTime *st, const char *api) {
    unsigned dow = (unsigned)(st->wDayOfWeek + 6) % 7;           /* Monday = 0 */
    unsigned h12 = st->wHour % 12 == 0 ? 12 : st->wHour % 12;
    for (size_t i = 0; pic[i];) {
        WCHAR c = pic[i];
        if (c == '\'') {
            i++;
            while (pic[i]) {
                if (pic[i] == '\'') {
                    if (pic[i + 1] == '\'') { out_put(o, '\''); i += 2; continue; }
                    i++;
                    break;
                }
                out_put(o, pic[i++]);
            }
            continue;
        }
        unsigned r = run_length(pic + i, c);
        if (is_date && c == 'd') {
            if (r == 1) out_num(o, st->wDay, 1);
            else if (r == 2) out_num(o, st->wDay, 2);
            else if (r == 3) out_str(o, day_abbr[dow]);
            else out_str(o, day_full[dow]);                      /* more than four count as four */
        } else if (is_date && c == 'M') {
            if (r == 1) out_num(o, st->wMonth, 1);
            else if (r == 2) out_num(o, st->wMonth, 2);
            else if (r == 3) out_str(o, month_abbr[st->wMonth - 1]);
            else out_str(o, month_full[st->wMonth - 1]);
        } else if (is_date && c == 'y') {
            if (r == 1)
                UNIMPL("%s: format picture \"y\": the documentation says both \"the last digit\" and \"assumed to be yy\"; "
                       "not implemented until Windows is observed", api);
            if (r == 2) out_num(o, st->wYear % 100, 2);
            else out_num(o, st->wYear, 4);                       /* yyy, yyyy, yyyyy: the full year */
        } else if (is_date && c == 'g') {
            UNIMPL("%s: format picture \"g\" (era): the era string \"A.D.\" of the Gregorian calendar was not verified", api);
        } else if (!is_date && (c == 'h' || c == 'H')) {
            unsigned hour = c == 'h' ? h12 : st->wHour;
            out_num(o, hour, r == 1 ? 1 : 2);                    /* more than two count as two */
        } else if (!is_date && c == 'm') {
            out_num(o, st->wMinute, r == 1 ? 1 : 2);
        } else if (!is_date && c == 's') {
            out_num(o, st->wSecond, r == 1 ? 1 : 2);
        } else if (!is_date && c == 't') {
            const char *marker = st->wHour < 12 ? "AM" : "PM";   /* LOCALE_S1159 / LOCALE_S2359 */
            if (r == 1) out_put(o, (uint8_t)marker[0]); else out_str(o, marker);
        } else {
            for (unsigned k = 0; k < r; k++) out_put(o, c);      /* any other character, each as itself */
        }
        i += r;
    }
}

#define FMT_LOCALE_FLAGS  (LOCALE_NOUSEROVERRIDE | LOCALE_USE_CP_ACP)

int rt_date_format(LCID locale, DWORD flags, const RtSystemTime *date, const WCHAR *format, WCHAR *buf, int len) {
    if (len < 0 || (!buf && len != 0)) return fail(ERROR_INVALID_PARAMETER);
    need_en_us(locale, L_NEUTRAL, "GetDateFormatW");
    /* LOCALE_NOUSEROVERRIDE with a format picture is ERROR_INVALID_FLAGS, checked before the other
     * flags (Wine test_GetDateFormatA: "Same as above but with LOCALE_NOUSEROVERRIDE"). */
    if (format && (flags & LOCALE_NOUSEROVERRIDE)) return fail(ERROR_INVALID_FLAGS);
    DWORD f = flags & ~(DWORD)FMT_LOCALE_FLAGS;
    const DWORD valid = DATE_SHORTDATE | DATE_LONGDATE | DATE_USE_ALT_CALENDAR | DATE_YEARMONTH | DATE_LTRREADING |
                        DATE_RTLREADING | DATE_AUTOLAYOUT;
    if ((f & ~valid) ||                                                        /* includes DATE_MONTHDAY: Windows 10 */
        __builtin_popcount(f & (DATE_SHORTDATE | DATE_LONGDATE | DATE_YEARMONTH)) > 1 ||
        (f & (DATE_LTRREADING | DATE_RTLREADING)) == (DATE_LTRREADING | DATE_RTLREADING) ||
        ((f & DATE_AUTOLAYOUT) && (f & (DATE_LTRREADING | DATE_RTLREADING))) ||
        (format && f))
        return fail(ERROR_INVALID_FLAGS);
    if (f & (DATE_USE_ALT_CALENDAR | DATE_LTRREADING | DATE_RTLREADING | DATE_AUTOLAYOUT))
        UNIMPL("GetDateFormatW: flags %#x include DATE_USE_ALT_CALENDAR, DATE_LTRREADING, DATE_RTLREADING or DATE_AUTOLAYOUT, "
               "which are not implemented", flags);

    RtSystemTime now;
    if (!date) { now_local(&now); date = &now; }
    /* The date must be valid: year 1601..9999 (the Gregorian calendar's range; the upper
     * limit was not verified), month, day.  The day of the week is recomputed. */
    if (date->wYear < 1601 || date->wYear > 9999 || date->wMonth < 1 || date->wMonth > 12 ||
        date->wDay < 1 || date->wDay > days_in_month(date->wYear, date->wMonth))
        return fail(ERROR_INVALID_PARAMETER);
    RtSystemTime st = *date;
    st.wDayOfWeek = (WORD)weekday(st.wYear, st.wMonth, st.wDay);

    static const WCHAR short_pic[] = { 'M', '/', 'd', '/', 'y', 'y', 'y', 'y', 0 };
    static const WCHAR long_pic[] = { 'd', 'd', 'd', 'd', ',', ' ', 'M', 'M', 'M', 'M', ' ', 'd', 'd', ',', ' ', 'y', 'y', 'y', 'y', 0 };
    static const WCHAR ym_pic[] = { 'M', 'M', 'M', 'M', ',', ' ', 'y', 'y', 'y', 'y', 0 };
    const WCHAR *pic = format ? format : (f & DATE_LONGDATE) ? long_pic : (f & DATE_YEARMONTH) ? ym_pic : short_pic;
    Out o = { buf, len, 0 };
    emit_picture(&o, pic, true, &st, "GetDateFormatW");
    return out_finish(&o);
}

int rt_time_format(LCID locale, DWORD flags, const RtSystemTime *t, const WCHAR *format, WCHAR *buf, int len) {
    if (len < 0 || (!buf && len != 0)) return fail(ERROR_INVALID_PARAMETER);
    need_en_us(locale, L_NEUTRAL, "GetTimeFormatW");
    if (format && !format[0])
        UNIMPL("GetTimeFormatW: an empty format picture: whether Windows treats it as NULL or returns the empty string was not verified");
    /* LOCALE_NOUSEROVERRIDE with a format picture is ERROR_INVALID_FLAGS, checked before the other
     * flags (MSDN: "LOCALE_NOUSEROVERRIDE can't be specified with a format string"; Wine
     * test_GetTimeFormatA). */
    if (format && (flags & LOCALE_NOUSEROVERRIDE)) return fail(ERROR_INVALID_FLAGS);
    DWORD f = flags & ~(DWORD)FMT_LOCALE_FLAGS;
    const DWORD valid = TIME_NOMINUTESORSECONDS | TIME_NOSECONDS | TIME_NOTIMEMARKER | TIME_FORCE24HOURFORMAT;
    if (f & ~valid) return fail(ERROR_INVALID_FLAGS);
    if (format && f)
        UNIMPL("GetTimeFormatW: flags %#x together with a format picture: what Windows does with the pair was not verified", flags);

    RtSystemTime now;
    if (!t) { now_local(&now); t = &now; }
    if (t->wHour > 23 || t->wMinute > 59 || t->wSecond > 59 || t->wMilliseconds > 999)
        return fail(ERROR_INVALID_PARAMETER);

    /* The locale format "h:mm:ss tt" with the flags applied: the minutes and seconds and
     * the marker each take their separator with them. */
    WCHAR pic_buf[16];
    const WCHAR *pic = format;
    if (!pic) {
        int n = 0;
        pic_buf[n++] = (f & TIME_FORCE24HOURFORMAT) ? 'H' : 'h';
        if (!(f & TIME_NOMINUTESORSECONDS)) {
            pic_buf[n++] = ':'; pic_buf[n++] = 'm'; pic_buf[n++] = 'm';
            if (!(f & TIME_NOSECONDS)) { pic_buf[n++] = ':'; pic_buf[n++] = 's'; pic_buf[n++] = 's'; }
        }
        if (!(f & TIME_NOTIMEMARKER)) { pic_buf[n++] = ' '; pic_buf[n++] = 't'; pic_buf[n++] = 't'; }
        pic_buf[n] = 0;
        pic = pic_buf;
    }
    Out o = { buf, len, 0 };
    emit_picture(&o, pic, false, t, "GetTimeFormatW");
    return out_finish(&o);
}

