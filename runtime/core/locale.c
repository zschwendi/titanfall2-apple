/* Day 1 is Monday (LOCALE_SDAYNAME1); LOCALE_IFIRSTDAYOFWEEK counts from Monday = 0, so
 * its "6" above is Sunday. */
static const char *const day_full[7]  = { "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday" };
static const char *const day_abbr[7]  = { "Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun" };
static const char *const month_full[12] = { "January", "February", "March", "April", "May", "June", "July", "August",
                                            "September", "October", "November", "December" };
static const char *const month_abbr[12] = { "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec" };

static bool locale_lookup(uint32_t type, const char **text, int32_t *num) {
    *num = -1;
    if (type >= LOCALE_SDAYNAME1 && type <= LOCALE_SDAYNAME7)             { *text = day_full[type - LOCALE_SDAYNAME1]; return true; }
    if (type >= LOCALE_SABBREVDAYNAME1 && type <= LOCALE_SABBREVDAYNAME7) { *text = day_abbr[type - LOCALE_SABBREVDAYNAME1]; return true; }
    if (type >= LOCALE_SMONTHNAME1 && type <= LOCALE_SMONTHNAME12)        { *text = month_full[type - LOCALE_SMONTHNAME1]; return true; }
    if (type >= LOCALE_SABBREVMONTHNAME1 && type <= LOCALE_SABBREVMONTHNAME12) { *text = month_abbr[type - LOCALE_SABBREVMONTHNAME1]; return true; }
    for (unsigned i = 0; i < sizeof locale_table / sizeof locale_table[0]; i++)
        if (locale_table[i].type == type) { *text = locale_table[i].text; *num = locale_table[i].num; return true; }
    return false;
}

int rt_locale_info(LCID locale, LCTYPE type, WCHAR *buf, int len) {
    if (len < 0 || (!buf && len != 0)) return fail(ERROR_INVALID_PARAMETER);
    need_en_us(locale, L_NEUTRAL, "GetLocaleInfoW");
    if (type & LOCALE_RETURN_GENITIVE_NAMES)
        UNIMPL("GetLocaleInfoW: LOCALE_RETURN_GENITIVE_NAMES (LCTYPE %#x): genitive month names are not in the table", type);
    bool want_number = (type & LOCALE_RETURN_NUMBER) != 0;
    uint32_t t = type & ~(LOCALE_NOUSEROVERRIDE | LOCALE_USE_CP_ACP | LOCALE_RETURN_NUMBER);
    const char *text;
    int32_t num;
    if (!locale_lookup(t, &text, &num))
        UNIMPL("GetLocaleInfoW: LCTYPE %#x (argument %#x) is not in the en-US table", t, type);
    if (want_number) {
        if (num < 0)
            UNIMPL("GetLocaleInfoW: LOCALE_RETURN_NUMBER with LCTYPE %#x, which has no numeric form", t);
        if (len == 0) return 2;                         /* sizeof(DWORD) in WCHARs */
        if (len < 2) return fail(ERROR_INSUFFICIENT_BUFFER);
        uint32_t v = (uint32_t)num;
        memcpy(buf, &v, sizeof v);
        return 2;
    }
    size_t n = strlen(text) + 1;
    if (len == 0) return (int)n;
    if ((size_t)len < n) return fail(ERROR_INSUFFICIENT_BUFFER);
    for (size_t i = 0; i < n; i++) buf[i] = (uint8_t)text[i];
    return (int)n;
}

BOOL rt_locale_enum_begin(DWORD flags, RtLocaleEnum *e) {
    /* Documented: LCID_INSTALLED cannot be used with LCID_SUPPORTED; 0 acts as LCID_SUPPORTED. */
    if ((flags & ~(DWORD)(LCID_INSTALLED | LCID_SUPPORTED | LCID_ALTERNATE_SORTS)) ||
        (flags & (LCID_INSTALLED | LCID_SUPPORTED)) == (LCID_INSTALLED | LCID_SUPPORTED))
        return fail(ERROR_INVALID_FLAGS);
    e->flags = flags;
    e->next = 0;
    return TRUE;
}

BOOL rt_locale_enum_next(RtLocaleEnum *e, WCHAR name[RT_LOCALE_ENUM_NAME_MAX]) {
    /* The one locale, unless only alternate sorts were asked for (there are none). */
    bool has_locales = e->flags == 0 || (e->flags & (LCID_INSTALLED | LCID_SUPPORTED));
    if (!has_locales || e->next >= 1) return FALSE;
    e->next++;
    static const char hex[] = "0123456789ABCDEF";
    LCID id = LANG_ENGLISH_US_LCID;
    for (int i = 0; i < 8; i++) name[i] = (WCHAR)(uint8_t)hex[(id >> (28 - 4 * i)) & 0xF];
    name[8] = 0;
    return TRUE;
}

